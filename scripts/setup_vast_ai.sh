#!/usr/bin/env bash
# Vast.ai / Multi-GPU CUDA One-Command Environment Bootstrapper for DCPA
# Tuned for 4x / 8x NVIDIA A100 SXM4 80GB, H100, H200, or Blackwell instances.
#
# Usage:
#   bash scripts/setup_vast_ai.sh                         # Fast in-container setup (reuses preinstalled PyTorch CUDA)
#   bash scripts/setup_vast_ai.sh --nvme-dir=/workspace/nvme_cache
#   bash scripts/setup_vast_ai.sh --with-rust             # Also install Rust toolchain & compile dcpa-cli release binary
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${REPO_ROOT}"

NVME_DIR="${DCPA_NVME_ROOT:-}"
INSTALL_RUST=0
PYTHON_BIN="${PYTHON_BIN:-python3}"

for arg in "$@"; do
  case "${arg}" in
    --nvme-dir=*) NVME_DIR="${arg#*=}" ;;
    --with-rust) INSTALL_RUST=1 ;;
    -h|--help)
      sed -n '2,9p' "$0"
      exit 0
      ;;
    *)
      echo "[ERROR] Unknown argument: ${arg}" >&2
      exit 1
      ;;
  esac
done

# Auto-detect fastest writable NVMe mount on Vast.ai / RunPod / Lambda
if [[ -z "${NVME_DIR}" ]]; then
  if [[ -d "/workspace" && -w "/workspace" ]]; then
    NVME_DIR="/workspace/nvme_cache"
  elif [[ -d "/raid" && -w "/raid" ]]; then
    NVME_DIR="/raid/dcpa_nvme"
  elif [[ -d "/nvme" && -w "/nvme" ]]; then
    NVME_DIR="/nvme/dcpa_cache"
  else
    NVME_DIR="${REPO_ROOT}/artifacts/nvme_cache"
  fi
fi

mkdir -p "${NVME_DIR}"/{data,cap_data,sft_data,checkpoints,logs,export,hf_cache,inductor_cache}

echo "======================================================================"
echo "  DCPA Vast.ai Multi-GPU Bootstrapper"
echo "  Repo     : ${REPO_ROOT}"
echo "  NVMe Dir : ${NVME_DIR}"
echo "  Free Disk: $(df -h "${NVME_DIR}" | awk 'NR==2 {print $4}')"
echo "======================================================================"

# 1. Install fast system CLI tools (zstd, aria2, tmux) when apt-get is available as root
if [[ "$(id -u)" -eq 0 ]] && command -v apt-get >/dev/null 2>&1; then
  MISSING_APT=()
  for pkg in zstd aria2 tmux git curl; do
    command -v "${pkg}" >/dev/null 2>&1 || MISSING_APT+=("${pkg}")
  done
  if [[ "${#MISSING_APT[@]}" -gt 0 ]]; then
    echo "[Sys] Installing fast archive/session tools: ${MISSING_APT[*]} ..."
    DEBIAN_FRONTEND=noninteractive apt-get update -qq >/dev/null 2>&1 || true
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${MISSING_APT[@]}" >/dev/null 2>&1 || true
  fi
fi

# 2. Check GPU & NVLink topology
if command -v nvidia-smi >/dev/null 2>&1; then
  echo "[GPU] Detected NVIDIA accelerators:"
  nvidia-smi --query-gpu=index,name,memory.total,driver_version --format=csv,noheader
  echo "[NVLink] Interconnect topology summary:"
  nvidia-smi topo -m 2>/dev/null | head -n 12 || true
else
  echo "[WARN] nvidia-smi not found in PATH."
fi

# 3. Reuse container PyTorch only if CUDA + F.grouped_mm (PyTorch >= 2.8) + live SM kernel execution succeed
#    (catches preinstalled cu126 PyTorch on Blackwell sm_120 / RTX 5090 that lacks sm_120 kernels!)
if ! "${PYTHON_BIN}" -c "
import sys, torch, torch.nn.functional as F
if not (torch.cuda.is_available() and hasattr(F, 'grouped_mm')):
    sys.exit(1)
x = torch.ones((4,), device='cuda', dtype=torch.bfloat16)
_ = (x + 1.0).sum().item()
sys.exit(0)
" >/dev/null 2>&1; then
  echo "[PyTorch] Installing/upgrading PyTorch >= 2.8 CUDA 12.8 wheels (cu128 supports SM80..SM120 / RTX 5090 & F.grouped_mm)..."
  "${PYTHON_BIN}" -m pip install -q --upgrade torch --index-url https://download.pytorch.org/whl/cu128
else
  echo "[PyTorch] Reusing preinstalled CUDA PyTorch with F.grouped_mm ($("${PYTHON_BIN}" -c 'import torch; print(torch.__version__)'))."
fi

# 4. Install lightweight DCPA Python dependencies (incl. tree-sitter Python & JavaScript)
echo "[Deps] Installing DCPA corpus, AST & training packages..."
"${PYTHON_BIN}" -m pip install -q \
  safetensors \
  datasets \
  huggingface_hub \
  hf_transfer \
  "tree-sitter>=0.23" \
  tree-sitter-python \
  tree-sitter-javascript \
  pyyaml \
  pytest

"${PYTHON_BIN}" -m pip install -q --no-deps --no-build-isolation -e "${REPO_ROOT}/dcpa-train-py"

# 5. Optional Rust CLI inference engine build
if [[ "${INSTALL_RUST}" -eq 1 ]]; then
  if ! command -v cargo >/dev/null 2>&1; then
    echo "[Rust] Installing rustup minimal toolchain..."
    curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --profile minimal
    # shellcheck disable=SC1091
    source "${HOME}/.cargo/env"
  fi
  echo "[Rust] Building dcpa-cli --release..."
  (cd "${REPO_ROOT}/dcpa-core-rs" && cargo build --release)
fi

# 6. Write persistent Vast.ai performance environment file (.vast_env.sh)
cat > "${REPO_ROOT}/.vast_env.sh" <<EOF
# Auto-generated by scripts/setup_vast_ai.sh
export DCPA_NVME_ROOT="${NVME_DIR}"
export PYTHONPATH="${REPO_ROOT}:${REPO_ROOT}/dcpa-train-py\${PYTHONPATH:+:\${PYTHONPATH}}"
export HF_HUB_ENABLE_HF_TRANSFER=1
export HF_XET_HIGH_PERFORMANCE=1
export HF_HOME="${NVME_DIR}/hf_cache"
export TOKENIZERS_PARALLELISM=false
export PYTORCH_CUDA_ALLOC_CONF="expandable_segments:True"
export TORCH_NCCL_ASYNC_ERROR_HANDLING=1
export NCCL_P2P_LEVEL=NVL
export CUDA_DEVICE_MAX_CONNECTIONS=8
export OMP_NUM_THREADS=4
EOF

# shellcheck disable=SC1091
source "${REPO_ROOT}/.vast_env.sh"

# 7. End-to-end CUDA + BF16 + F.grouped_mm smoke check
"${PYTHON_BIN}" -c "
import torch
import torch.nn.functional as F
from dcpa.config import DCPAConfig
from dcpa.model import DCPAModel

print(f'[Verify] PyTorch={torch.__version__} | CUDA={torch.cuda.is_available()} | GPUs={torch.cuda.device_count()}')
if torch.cuda.is_available():
    for idx in range(torch.cuda.device_count()):
        p = torch.cuda.get_device_properties(idx)
        print(f'  GPU {idx}: {p.name} | {p.total_memory / (1024**3):.1f} GB | SM {p.major}.{p.minor}')
    has_gmm = hasattr(F, 'grouped_mm')
    print(f'[Verify] torch.nn.functional.grouped_mm available: {has_gmm}')
cfg = DCPAConfig.moe_2_6b()
print(f'[Verify] Flagship preset moe_2_6b validated: d_concept={cfg.d_concept}, experts={cfg.num_experts} (Top-{cfg.top_k_experts})')
"

echo "======================================================================"
echo "  [READY] Environment configured! Start training immediately with:"
echo "    bash scripts/launch_vast_train.sh --tmux=dcpa"
echo "======================================================================"
